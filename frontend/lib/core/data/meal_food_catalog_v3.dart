import 'dart:convert';

import 'package:flutter/widgets.dart';

/// Food discovery vocabulary for IAMINA.
///
/// Coverage is deliberately broader than a nutrient database row set: one
/// visual food concept can later map to several validated nutrient records.
/// Current scope prioritises Morocco + GCC, while retaining common universal
/// foods. Representative regional foods were cross-checked against HCP/FAO
/// TMCA (Morocco, 2026), Visit Qatar cuisine guidance, and Experience Abu
/// Dhabi Emirati cuisine guidance. Nutrient values are intentionally not
/// stored here.
enum MealFoodCategory {
  breadGrain,
  moroccanDish,
  gulfDish,
  meatPoultry,
  fishSeafood,
  egg,
  dairy,
  legume,
  vegetable,
  fruit,
  nutSeed,
  fatSauce,
  drink,
  sweetDessert,
  snackFastFood,
  saladMeal,
  soup,
  other,
}

enum MealFoodRegion { universal, morocco, gulf }

enum MealFoodMoment { breakfast, lunch, dinner, snack, ramadan }

class MealFoodItem {
  final String id;
  final String fr;
  final String en;
  final String ar;
  final List<String> aliases;
  final MealFoodCategory category;
  final Set<MealFoodRegion> regions;
  final Set<MealFoodMoment> moments;
  final String visual;

  const MealFoodItem(
    this.id,
    this.fr,
    this.en,
    this.ar, {
    this.aliases = const <String>[],
    this.category = MealFoodCategory.other,
    this.regions = const <MealFoodRegion>{MealFoodRegion.universal},
    this.moments = const <MealFoodMoment>{},
    this.visual = '🍽️',
  });

  String plainLabelFor(Locale locale) {
    if (locale.languageCode == 'ar') return ar;
    if (locale.languageCode == 'en') return en;
    return fr;
  }

  String labelFor(Locale locale) => '$visual ${plainLabelFor(locale)}';

  String get pictogramKey => id;

  String get searchable => <String>[id, fr, en, ar, ...aliases].join(' ');
}

