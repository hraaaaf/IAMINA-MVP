List<String> decodeMealItemIds(String? raw) {
  if (raw == null || raw.trim().isEmpty) return const <String>[];
  try {
    final decoded = jsonDecode(raw);
    if (decoded is! List) return const <String>[];
    return decoded
        .whereType<String>()
        .where(_mealFoodById.containsKey)
        .toList(growable: false);
  } catch (_) {
    return const <String>[];
  }
}

String encodeMealItemIds(Iterable<String> ids) => jsonEncode(
  ids.where(_mealFoodById.containsKey).toSet().toList(growable: false),
);

String foldMealText(String value) => value
    .toLowerCase()
    .replaceAll('œ', 'oe')
    .replaceAll(RegExp('[àáâäãå]'), 'a')
    .replaceAll(RegExp('[ç]'), 'c')
    .replaceAll(RegExp('[èéêë]'), 'e')
    .replaceAll(RegExp('[ìíîï]'), 'i')
    .replaceAll(RegExp('[ñ]'), 'n')
    .replaceAll(RegExp('[òóôöõ]'), 'o')
    .replaceAll(RegExp('[ùúûü]'), 'u')
    .replaceAll(RegExp('[ýÿ]'), 'y')
    .replaceAll(RegExp(r'[^a-z0-9\u0600-\u06ff]+'), ' ')
    .trim();

int _mealSearchScore(MealFoodItem item, String folded) {
  final values = <String>[item.fr, item.en, item.ar, ...item.aliases]
      .map(foldMealText)
      .where((value) => value.isNotEmpty)
      .toList(growable: false);
  if (values.any((value) => value == folded)) return 100;
  if (values.any((value) => value.startsWith(folded))) return 80;
  if (values.any((value) => value.contains(folded))) return 60;
  final terms = folded.split(' ').where((term) => term.isNotEmpty).toList();
  if (terms.isNotEmpty && terms.every((term) => foldMealText(item.searchable).contains(term))) {
    return 40;
  }
  return 0;
}

List<MealFoodItem> searchMealFoods(String query, {int limit = 12}) {
  final folded = foldMealText(query);
  if (folded.length < 2) return const <MealFoodItem>[];
  final scored = <MapEntry<MealFoodItem, int>>[];
  for (final item in mealFoodCatalog) {
    final score = _mealSearchScore(item, folded);
    if (score > 0) scored.add(MapEntry(item, score));
  }
  scored.sort((a, b) {
    final byScore = b.value.compareTo(a.value);
    if (byScore != 0) return byScore;
    return a.key.fr.compareTo(b.key.fr);
  });
  return scored.take(limit).map((entry) => entry.key).toList(growable: false);
}

List<MealFoodItem> matchRecognizedMealFoods(Iterable<String> recognized) {
  final found = <String, MealFoodItem>{};
  for (final raw in recognized) {
    final needle = foldMealText(raw);
    if (needle.isEmpty) continue;
    final ranked = searchMealFoods(raw, limit: 1);
    if (ranked.isNotEmpty) found[ranked.first.id] = ranked.first;
  }
  return found.values.take(8).toList(growable: false);
}
